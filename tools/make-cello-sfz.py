def pizzicato_file():
    """피치카토: 층 하나, 벨로시티가 크기(25~100 %)와 밝기, 녹음의 끝까지 울린다. 같은 음을 다시 뜯으면 앞 음을 끈다"""
    pat = re.compile(r"^(C|Eb|Gb|A)(\d)_(\d)$")
    rows = []
    for r in parse(PIZZICATO, ("name", "level", "cents", "dur")):
        m = pat.match(r["name"])
        r.update(midi=midi_of(m.group(1), m.group(2)), layer="all", rr=int(m.group(3)))
