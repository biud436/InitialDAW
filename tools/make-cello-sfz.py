def write_if_changed(path, text):
    """내용이 다를 때만 쓴다"""
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if old == text:
        return False
    tmp = path + ".part"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, path)
    return True


def main():
    ap = argparse.ArgumentParser(description="Karoryfer x bigcat 첼로 샘플 곁에 InitialDAW 의 SFZ 를 쓴다")
    ap.add_argument("library", help="Karoryfer_Bigcat_cello 폴더 (Samples/ 가 있는 곳)")
    ap.add_argument("--out", help="SFZ 를 쓸 폴더 (기본: <library>/InitialDAW)")
    ap.add_argument("--dynamics", choices=("select", "xfade"), default="select",
                    help="select: 음을 시작할 때 CC1 로 층을 고른다 (기본), xfade: CC1 이 이웃한 두 층을 섞는다 (비교용)")
    args = ap.parse_args()
    samples = os.path.join(args.library, "Samples")
    missing = [f"{d}/{r.split()[0]}.wav" for d, t in (("sus", SUSTAIN), ("staccato", STACCATO), ("pizzcato", PIZZICATO))
               for r in t.strip().splitlines() if not os.path.exists(os.path.join(samples, d, r.split()[0] + ".wav"))]
    if missing:
        print(f"make-cello-sfz: {samples} 에 샘플 {len(missing)}개가 없습니다 (처음: {missing[0]})", file=sys.stderr)
        return 1
    out = args.out or os.path.join(args.library, "InitialDAW")
    os.makedirs(out, exist_ok=True)
    rel = os.path.relpath(samples, out).replace(os.sep, "/") + "/"
    files = {"cello-legato.sfz": bowed_file("legato", args.dynamics), "cello-sustain.sfz": bowed_file("attack", args.dynamics),
             "cello-staccato.sfz": staccato_file(), "cello-pizzicato.sfz": pizzicato_file()}
    changed = [name for name, text in files.items() if write_if_changed(os.path.join(out, name), text.replace("default_path=../Samples/", f"default_path={rel}"))]
    if changed:
        print(f"[InitialDAW] 첼로 SFZ 를 썼습니다: {out} ({', '.join(changed)})")
    return 0


